        path: '/patients',
        summary: 'Register a patient',
        description: 'Role: receptionist only. The patient_number is generated by the server and cannot be sent.',
        tags: ['Patients'],
        security: [['sanctum' => []]],
        requestBody: new OA\RequestBody(
            required: true,
            content: new OA\JsonContent(allOf: [
                new OA\Schema(ref: '#/components/schemas/PatientInput'),
                new OA\Schema(required: ['first_name', 'last_name', 'gender', 'date_of_birth', 'phone']),
