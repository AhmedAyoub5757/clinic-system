        responses: [
            new OA\Response(
                response: 200,
                description: 'The patient',
                content: new OA\JsonContent(allOf: [
                    new OA\Schema(ref: '#/components/schemas/SuccessEnvelope'),
                    new OA\Schema(properties: [
                        new OA\Property(property: 'data', ref: '#/components/schemas/Patient'),
                    ]),
