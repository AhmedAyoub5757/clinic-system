    #[OA\Put(
        path: '/patients/{id}',
        summary: 'Update a patient (partial)',
        description: 'Role: receptionist only. Send only the fields that changed.',
        tags: ['Patients'],
        security: [['sanctum' => []]],
        parameters: [
            new OA\Parameter(name: 'id', in: 'path', required: true, schema: new OA\Schema(type: 'integer')),
        ],
        requestBody: new OA\RequestBody(
            required: true,
            content: new OA\JsonContent(ref: '#/components/schemas/PatientInput')
        ),
        responses: [
            new OA\Response(
                response: 200,
                description: 'Patient updated',
                content: new OA\JsonContent(allOf: [
                    new OA\Schema(ref: '#/components/schemas/SuccessEnvelope'),
                    new OA\Schema(properties: [
                        new OA\Property(property: 'data', ref: '#/components/schemas/Patient'),
